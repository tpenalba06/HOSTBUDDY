export const I18N_KEYS = Object.keys(translations.fr);
export function missingTranslationKeys(locale: Locale) { return I18N_KEYS.filter((key) => !translations[locale][key]); }

const LocaleContext = createContext<{ locale: Locale; setLocale: (locale: Locale) => void; t: (key: string) => string }>({ locale: "fr", setLocale: () => {}, t: (key) => translations.fr[key] ?? "" });
const matchLocale = (value?: string | null): Locale => { const short = value?.toLowerCase().split("-")[0]; return LOCALES.includes(short as Locale) ? short as Locale : "fr"; };

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fr");
  useEffect(() => { const saved = window.sessionStorage.getItem("hostbuddy.locale") ?? window.localStorage.getItem("hostbuddy.locale"); setLocaleState(matchLocale(saved ?? window.navigator.language)); }, []);
  const setLocale = (next: Locale) => { setLocaleState(next); window.sessionStorage.setItem("hostbuddy.locale", next); window.localStorage.setItem("hostbuddy.locale", next); document.documentElement.lang = next; };
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  const value = useMemo(() => ({ locale, setLocale, t: (key: string) => { const value = translations[locale][key]; if (!value) { if (import.meta.env.DEV) console.warn(`[i18n] Missing ${locale}: ${key}`); return translations.fr[key] ?? ""; } return value; } }), [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}
export const useI18n = () => useContext(LocaleContext);
export const translateStatic = (locale: Locale, key: string) => translations[locale][key] ?? translations.fr[key] ?? "";
